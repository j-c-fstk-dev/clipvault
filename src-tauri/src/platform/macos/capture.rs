//! macOS clipboard watcher.
//!
//! macOS has no notification for clipboard changes, so, like other clipboard
//! managers, the watcher polls `NSPasteboard.changeCount` (a counter read,
//! which does not count as reading the clipboard) and reads the content when
//! it changes. Since macOS 15.4 the user decides whether apps may read the
//! clipboard in the background: see [`access`].

use std::io;
use std::path::PathBuf;
use std::process::Command;
use std::sync::atomic::{AtomicBool, AtomicIsize, Ordering};
use std::sync::{Arc, Mutex, MutexGuard};
use std::thread::{self, JoinHandle};
use std::time::Duration;

use objc2::rc::autoreleasepool;
use objc2::runtime::{AnyObject, NSObjectProtocol};
use objc2::sel;
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSBitmapImageRepPropertyKey, NSPasteboard,
    NSPasteboardAccessBehavior,
};
use objc2_foundation::{NSData, NSDictionary, NSString, NSURL};

use super::serve::ClipboardHandle;
use crate::model::{Captured, ClipboardAccess};

pub(crate) type BoxError = Box<dyn std::error::Error + Send + Sync>;
pub(crate) type Result<T> = std::result::Result<T, BoxError>;

/// How often the change counter is checked.
const POLL_INTERVAL: Duration = Duration::from_millis(500);
/// Text larger than this is not stored.
const MAX_TEXT_BYTES: usize = 16 * 1024 * 1024;
/// Images larger than this are not stored.
const MAX_IMAGE_BYTES: usize = 256 * 1024 * 1024;

pub(crate) const TEXT: &str = "public.utf8-plain-text";
pub(crate) const HTML: &str = "public.html";
pub(crate) const FILE_URL: &str = "public.file-url";
pub(crate) const PNG: &str = "public.png";
const TIFF: &str = "public.tiff";

/// Image types read as they are, best first. TIFF, what many Mac apps put
/// on the clipboard, comes last and is converted to PNG.
const IMAGE_TYPES: &[(&str, &str)] = &[
    (PNG, "image/png"),
    ("public.jpeg", "image/jpeg"),
    ("org.webmproject.webp", "image/webp"),
    ("com.compuserve.gif", "image/gif"),
    ("com.microsoft.bmp", "image/bmp"),
];

/// Types that password managers and other apps add to content that should
/// not be kept in a history (see nspasteboard.org).
const SECRET_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
    "net.antelle.keeweb",
];

/// State shared by the watcher and [`ClipboardHandle`].
pub(crate) struct Shared {
    /// Held while reading or writing, so the watcher never reads our own
    /// content halfway through being written.
    lock: Mutex<()>,
    /// Change count of the content we put on the clipboard ourselves.
    pub(crate) own_count: AtomicIsize,
}

impl Shared {
    pub(crate) fn lock(&self) -> MutexGuard<'_, ()> {
        self.lock.lock().unwrap_or_else(|e| e.into_inner())
    }
}

/// What the user allowed for background clipboard reads, or `None` when
/// there is no such setting (before macOS 15.4) or no choice was made yet.
pub fn access() -> Option<ClipboardAccess> {
    autoreleasepool(|_| {
        let pasteboard = NSPasteboard::generalPasteboard();
        if !pasteboard.respondsToSelector(sel!(accessBehavior)) {
            return None;
        }
        match pasteboard.accessBehavior() {
            NSPasteboardAccessBehavior::AlwaysAllow => Some(ClipboardAccess::Allowed),
            NSPasteboardAccessBehavior::Ask => Some(ClipboardAccess::Ask),
            NSPasteboardAccessBehavior::AlwaysDeny => Some(ClipboardAccess::Denied),
            _ => None,
        }
    })
}

/// With "Ask", macOS shows an alert on every read, so the watcher waits
/// until the user allows ClipVault in System Settings. With no choice made
/// yet it reads: either there is no alert, or the first one makes ClipVault
/// appear in System Settings.
fn may_read(access: Option<ClipboardAccess>) -> bool {
    !matches!(access, Some(ClipboardAccess::Ask | ClipboardAccess::Denied))
}

/// Opens System Settings at Privacy & Security, where "Paste from Other
/// Apps" lists ClipVault.
pub fn open_access_settings() -> std::result::Result<(), String> {
    let status = Command::new("/usr/bin/open")
        .arg("x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard")
        .status()
        .map_err(|e| format!("cannot open System Settings: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err("cannot open System Settings".into())
    }
}

pub struct Watcher {
    shared: Arc<Shared>,
}

impl Watcher {
    pub fn connect() -> Result<Self> {
        Ok(Self {
            shared: Arc::new(Shared {
                lock: Mutex::new(()),
                own_count: AtomicIsize::new(isize::MIN),
            }),
        })
    }

    /// A handle other threads use to put content on the clipboard.
    pub fn handle(&self) -> ClipboardHandle {
        ClipboardHandle::new(self.shared.clone())
    }

    /// Runs the watcher on its own thread, calling `on_capture` for every
    /// clipboard change while `paused` is false. The current clipboard
    /// content is captured once at startup.
    pub fn spawn<F>(self, paused: Arc<AtomicBool>, on_capture: F) -> io::Result<JoinHandle<()>>
    where
        F: FnMut(Captured) + Send + 'static,
    {
        thread::Builder::new()
            .name("clipboard-watcher".into())
            .spawn(move || self.run(&paused, on_capture))
    }

    fn run(self, paused: &AtomicBool, mut on_capture: impl FnMut(Captured)) {
        let mut seen = None;
        let mut waiting = false;
        loop {
            let count = autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount());
            if seen != Some(count) {
                if !may_read(access()) {
                    // Read once the user allows it.
                    if !waiting {
                        log::info!("waiting for permission to read the clipboard");
                        waiting = true;
                    }
                } else {
                    waiting = false;
                    seen = Some(count);
                    if !paused.load(Ordering::Relaxed) {
                        match self.read() {
                            Ok(Some(captured)) => on_capture(captured),
                            Ok(None) => {}
                            Err(err) => log::warn!("could not read clipboard: {err}"),
                        }
                    }
                }
            }
            thread::sleep(POLL_INTERVAL);
        }
    }

    fn read(&self) -> Result<Option<Captured>> {
        let _guard = self.shared.lock();
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            if pasteboard.changeCount() == self.shared.own_count.load(Ordering::Relaxed) {
                return Ok(None);
            }
            let types: Vec<String> = pasteboard
                .types()
                .map(|types| types.iter().map(|t| t.to_string()).collect())
                .unwrap_or_default();
            if is_secret(&types) {
                log::debug!("skipping clipboard content marked as secret");
                return Ok(None);
            }

            if has(&types, FILE_URL) {
                let paths = file_paths(&pasteboard);
                if !paths.is_empty() {
                    return Ok(Some(Captured::Files { paths }));
                }
            }

            // Plain text wins over images, as on Linux: office apps put a
            // picture next to the text, apps copying a picture put no text.
            let Some(text) = read_text(&pasteboard, &types) else {
                return Ok(read_image(&pasteboard, &types));
            };
            let html = has(&types, HTML)
                .then(|| pasteboard.stringForType(&NSString::from_str(HTML)))
                .flatten()
                .map(|html| html.to_string())
                .filter(|html| !html.trim().is_empty());
            Ok(Some(Captured::Text { text, html }))
        })
    }
}

fn has(types: &[String], wanted: &str) -> bool {
    types.iter().any(|t| t == wanted)
}

fn is_secret(types: &[String]) -> bool {
    types.iter().any(|t| SECRET_TYPES.contains(&t.as_str()))
}

/// Finder puts one item with a file URL per copied file.
fn file_paths(pasteboard: &NSPasteboard) -> Vec<PathBuf> {
    let file_url = NSString::from_str(FILE_URL);
    pasteboard
        .pasteboardItems()
        .map(|items| {
            items
                .iter()
                .filter_map(|item| item.stringForType(&file_url))
                .filter_map(|url| NSURL::URLWithString(&url))
                // Resolves file reference URLs (file:///.file/id=...).
                .filter_map(|url| url.filePathURL())
                .filter_map(|url| url.path())
                .map(|path| PathBuf::from(path.to_string()))
                .collect()
        })
        .unwrap_or_default()
}

fn read_text(pasteboard: &NSPasteboard, types: &[String]) -> Option<String> {
    if !has(types, TEXT) {
        return None;
    }
    let text = pasteboard
        .stringForType(&NSString::from_str(TEXT))?
        .to_string();
    if text.len() > MAX_TEXT_BYTES {
        log::info!("skipping {} MiB of text", text.len() / (1024 * 1024));
        return None;
    }
    let text = text.trim_end_matches('\0').to_string();
    (!text.trim().is_empty()).then_some(text)
}

/// The image type to read, and its MIME type once read.
fn image_type(types: &[String]) -> Option<(&'static str, &'static str)> {
    IMAGE_TYPES
        .iter()
        .copied()
        .find(|(uti, _)| has(types, uti))
        .or_else(|| has(types, TIFF).then_some((TIFF, "image/png")))
}

fn read_image(pasteboard: &NSPasteboard, types: &[String]) -> Option<Captured> {
    let (uti, mime) = image_type(types)?;
    let data = pasteboard.dataForType(&NSString::from_str(uti))?;
    if data.length() > MAX_IMAGE_BYTES {
        log::info!("skipping a {} MiB image", data.length() / (1024 * 1024));
        return None;
    }
    let bytes = if uti == TIFF {
        to_png(&data)?
    } else {
        data.to_vec()
    };
    (!bytes.is_empty()).then(|| Captured::Image {
        bytes,
        mime: mime.to_string(),
    })
}

/// Converts an image macOS can decode (TIFF, JPEG, GIF, BMP, WebP) to PNG.
pub(crate) fn to_png(data: &NSData) -> Option<Vec<u8>> {
    let image = NSBitmapImageRep::imageRepWithData(data)?;
    let properties = NSDictionary::<NSBitmapImageRepPropertyKey, AnyObject>::new();
    // SAFETY: an empty property dictionary is valid for every file type.
    let png = unsafe {
        image.representationUsingType_properties(NSBitmapImageFileType::PNG, &properties)
    };
    png.map(|png| png.to_vec())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn types(names: &[&str]) -> Vec<String> {
        names.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn secrets_are_detected() {
        assert!(is_secret(&types(&[TEXT, "org.nspasteboard.ConcealedType"])));
        assert!(is_secret(&types(&["com.agilebits.onepassword", TEXT])));
        assert!(!is_secret(&types(&[TEXT, HTML])));
    }

    #[test]
    fn prefers_original_images_over_tiff() {
        assert_eq!(
            image_type(&types(&[TIFF, "public.jpeg"])),
            Some(("public.jpeg", "image/jpeg"))
        );
        assert_eq!(image_type(&types(&[TIFF, PNG])), Some((PNG, "image/png")));
        assert_eq!(image_type(&types(&[TIFF])), Some((TIFF, "image/png")));
        assert_eq!(image_type(&types(&[TEXT])), None);
    }

    #[test]
    fn waits_for_permission_only_when_asked_or_denied() {
        assert!(may_read(None));
        assert!(may_read(Some(ClipboardAccess::Allowed)));
        assert!(!may_read(Some(ClipboardAccess::Ask)));
        assert!(!may_read(Some(ClipboardAccess::Denied)));
    }

    /// Writes to and reads from the real clipboard, so it replaces whatever
    /// is on it.
    #[test]
    fn copies_text_and_reads_it_back() {
        let watcher = Watcher::connect().unwrap();
        let handle = watcher.handle();
        let out = crate::model::Outgoing::Text {
            text: "ClipVault test".into(),
            html: Some("<b>ClipVault test</b>".into()),
        };
        handle.set(&out).unwrap();
        // Our own content is skipped...
        assert_eq!(watcher.read().unwrap(), None);
        // ...but read like any other once it is not ours.
        watcher
            .shared
            .own_count
            .store(isize::MIN, Ordering::Relaxed);
        match watcher.read().unwrap() {
            Some(Captured::Text { text, html }) => {
                assert_eq!(text, "ClipVault test");
                assert!(html.unwrap().contains("ClipVault test"));
            }
            other => panic!("unexpected {other:?}"),
        }
    }
}
